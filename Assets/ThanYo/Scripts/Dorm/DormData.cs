public class TenantInfo
{
    public string id, name, room;
    public int portrait;            // รูป Resources/Dorm/tenant-N
    public string[] traces;         // ร่องรอยประจำตัว (เห็นผ่านตาแมว)
    public string decoy;            // ตัวปลอมแบบ "ร่องรอยผิด" จะแสดงอันนี้แทน traces[0]
    public string[] interview;      // สัมภาษณ์ครั้งแรก (ใช้ 1 แอ็กชัน)
    public string chat;             // คุยครั้งต่อไป (ฟรี)
    public string clueId;           // เบาะแสที่ได้จากการสัมภาษณ์
    public string[] doorLines;      // ประโยคที่พูดหน้าประตูตอนกลางคืน...
    public string[] doorTraces;     // ...และร่องรอยที่ประโยคนั้น "ต้อง" ทิ้งไว้ (คนจริงมี ของปลอมอาจไม่มี)
    public Color top, bottom, skin, hair;
    public bool bald, shortSleeves, shorts;
}

public class ClueInfo
{
    public string id, title, body;
    public ClueInfo(string id, string title, string body) { this.id = id; this.title = title; this.body = body; }
}

public class TruthInfo
{
    public string id, title, body;
    public string[] clues;          // เบาะแสที่เกี่ยว
    public int need;                // ต้องมีกี่ชิ้นถึงปลดล็อก
}

